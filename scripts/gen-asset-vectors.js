// Captures real AssetStore responses from a local chain into luau/test/vectors_assetstore.h, which
// the harness checks the engine-agnostic resolver against.
// Run after deploy.js with anvil up:  node scripts/gen-asset-vectors.js
const { ethers } = require("ethers");
const fs = require("fs"), path = require("path");
const { provider, contracts } = require("../bridge/src/chain");
const cfg = require("../bridge/src/config");
const assets = require("./assets");

const seed = (n, salt) => { const b = Buffer.alloc(n); let x = salt; for (let i = 0; i < n; i++) { x = (Math.imul(x, 1103515245) + 12345) >>> 0; b[i] = x >>> 24; } return b; };

(async () => {
  const signer = new ethers.NonceManager(new ethers.Wallet("0x7c852118294e51e653712a81e05800f419141751be58f605c371e15141b007a6", provider)); // anvil #3
  const store = contracts.assetStore;
  const A = cfg.addresses.AssetStore;
  const call = (data) => provider.call({ to: A, data });

  const small = Buffer.from(JSON.stringify({ name: "Wizard Hat", kind: "accessory", license: "CC0-1.0" }));
  const s = await assets.storeBytes(small, { mime: "application/json", signer });
  const twoChunk = seed(30_000, 11);   // 2 chunks: 24,575 + 5,425
  const t = await assets.storeBytes(twoChunk, { mime: "application/octet-stream", signer });

  const iface = store.interface;
  const v = {
    chainId: cfg.chainId, store: A,
    small: {
      blobId: s.blobId.toString(), uri: s.uri, contentHash: s.contentHash, size: small.length, mime: "application/json",
      bytesHex: ethers.hexlify(small), chunks: s.chunks,
      readCalldata: iface.encodeFunctionData("read", [s.blobId]),
      readResult: await call(iface.encodeFunctionData("read", [s.blobId])),
      chunksOfCalldata: iface.encodeFunctionData("chunksOf", [s.blobId]),
      chunksOfResult: await call(iface.encodeFunctionData("chunksOf", [s.blobId])),
      blobCalldata: iface.encodeFunctionData("blob", [s.blobId]),
      blobResult: await call(iface.encodeFunctionData("blob", [s.blobId])),
      blobOfCalldata: iface.encodeFunctionData("blobOf", [s.contentHash]),
      blobOfResult: await call(iface.encodeFunctionData("blobOf", [s.contentHash])),
      code0: await provider.getCode(s.chunks[0]),
    },
    two: {
      blobId: t.blobId.toString(), uri: t.uri, contentHash: t.contentHash, size: twoChunk.length, seedSalt: 11, chunks: t.chunks,
      readResult: await call(iface.encodeFunctionData("read", [t.blobId])),
      chunksOfResult: await call(iface.encodeFunctionData("chunksOf", [t.blobId])),
      blobResult: await call(iface.encodeFunctionData("blob", [t.blobId])),
      readRangeCalldata: iface.encodeFunctionData("readRange", [t.blobId, 24_570, 10]),
      readRangeResult: await call(iface.encodeFunctionData("readRange", [t.blobId, 24_570, 10])),
      readRangeExpected: ethers.hexlify(twoChunk.subarray(24_570, 24_580)),
      code0: await provider.getCode(t.chunks[0]),
      code1: await provider.getCode(t.chunks[1]),
    },
  };
  // MSVC rejects a string literal over 16,380 bytes (C2026); adjacent literals concatenate.
  const LIT = 4000;
  const esc = (x) => {
    const v = typeof x === "string" ? x : x.toString();
    if (v.length <= LIT) return JSON.stringify(v);
    const parts = [];
    for (let i = 0; i < v.length; i += LIT) parts.push(JSON.stringify(v.slice(i, i + LIT)));
    return parts.join("
    ");
  };
  let h = "// Generated by scripts/gen-asset-vectors.js from a local anvil run. Do not edit.\n#pragma once\nnamespace assetstore_vectors {\n";
  const emit = (prefix, o) => { for (const [k, val] of Object.entries(o)) {
    if (Array.isArray(val)) h += `static const char* ${prefix}${k}[] = {${val.map(esc).join(", ")}};\nstatic const int ${prefix}${k}_n = ${val.length};\n`;
    else if (typeof val === "object") emit(prefix + k + "_", val);
    else if (typeof val === "number") h += `static const unsigned long long ${prefix}${k} = ${val}ULL;\n`;
    else h += `static const char* ${prefix}${k} = ${esc(val)};\n`;
  } };
  emit("", v);
  h += "} // namespace assetstore_vectors\n";
  const out = path.join(__dirname, "..", "luau", "test", "vectors_assetstore.h");
  fs.writeFileSync(out, h);
  console.log("wrote", out, (h.length / 1024).toFixed(0) + " KB");
})().catch((e) => { console.error(e); process.exit(1); });
